def require(condition: bool, label: str) -> None:
    if not condition:
        raise RuntimeError(label)


def canonical(value: Any) -> str:
    return json.dumps(
        value, sort_keys=True, separators=(",", ":"), allow_nan=False
    )


def digest(value: Any) -> str:
    return hashlib.sha256(canonical(value).encode("utf-8")).hexdigest()


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def qstr(value: Q | int) -> str:
    return str(Q(value))


def strict_pairs(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        require(key not in result, f"duplicate JSON key: {key}")
        result[key] = value
    return result


def strict_json(path: Path) -> dict[str, Any]:
    value = json.loads(
        path.read_text(encoding="utf-8"),
        object_pairs_hook=strict_pairs,
        parse_float=lambda token: (_ for _ in ()).throw(
            ValueError(f"JSON float forbidden: {token}")
        ),
        parse_constant=lambda token: (_ for _ in ()).throw(
            ValueError(f"JSON constant forbidden: {token}")
        ),
    )
    require(type(value) is dict, f"top-level JSON object: {path.name}")
    return value


def load_closed(path: Path) -> dict[str, Any]:
    document = strict_json(path)
    require(
        set(document) == {"schema", "result", "result_sha256"},
        f"closed envelope: {path.name}",
    )
    require(document["schema"] == CLOSED_SCHEMAS[path.name], f"schema: {path.name}")
    require(
        document["result_sha256"] == digest(document["result"]),
        f"result digest: {path.name}",
    )
    return document["result"]


def arb_bounds(value: arb) -> tuple[Q, Q]:
    return r121.arb_pair(value)


def interval_strings(value: arb, guard: Q = Q(0)) -> list[str]:
    lower, upper = arb_bounds(value)
    return [qstr(lower - guard), qstr(upper + guard)]


def guarded_abs_upper(value: arb) -> Q:
    lower, upper = arb_bounds(value)
    return max(abs(lower - ENCLOSURE_GUARD), abs(upper + ENCLOSURE_GUARD))


def row_id(kind: str, payload: list[Any]) -> str:
    return f"round130-{kind}:" + digest([f"round130-{kind}-v1", *payload])


def with_hash(row: dict[str, Any]) -> dict[str, Any]:
    require("row_sha256" not in row, "row hash absent before closure")
    row["row_sha256"] = digest(row)
    return row


def verification_passed(result: dict[str, Any]) -> bool:
    return result.get("status", result.get("verdict")) == "PASS"


