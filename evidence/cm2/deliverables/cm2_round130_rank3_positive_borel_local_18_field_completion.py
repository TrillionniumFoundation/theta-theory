def rows_digest(rows: list[dict[str, Any]]) -> str:
    require(
        all(row.get("row_sha256") == digest({
            key: value for key, value in row.items() if key != "row_sha256"
        }) for row in rows),
        "row closure",
    )
    return digest(rows)


