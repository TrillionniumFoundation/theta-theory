    t_guard = tuple(
        Q(value)
        for value in r129["positive_Borel_family_root_contract"]["uniform_t_guard"]
    )
    a3_zero = c123.adapted3(seed, t_guard, Q(0), Q(0)).value
    a3_one = c123.adapted3(seed, t_guard, Q(1), Q(1)).value
    whole = c123.adapted3(seed, t_guard, Q(0), Q(1))
    ratio = (a3_zero - a3_one) / r121.aq(DELTA)
    derivative_ratio = -whole.gradient[0] / r121.aq(DELTA)
    ratio_lower, ratio_upper = arb_bounds(ratio)
    derivative_lower, derivative_upper = arb_bounds(derivative_ratio)
    require(192 < ratio_lower <= ratio_upper < 193, "family U3 length")
    require(
        192 < derivative_lower <= derivative_upper < 193,
        "family U3 derivative",
    )

    endpoint_rows: list[dict[str, Any]] = []
    helper_endpoint_rows: list[dict[str, Any]] = []
    for frozen in sorted(
        r123["stage3_endpoint_rows"], key=lambda row: row["natural_index_j"]
    ):
        level = int(frozen["natural_index_j"])
        frozen_lower, frozen_upper = map(Q, frozen["x_dyadic_bracket"])
        center = (frozen_lower + frozen_upper) / 2
        lower = center - STAGE3_GUARD_RADIUS
        upper = center + STAGE3_GUARD_RADIUS
        require(0 < lower < upper < 1, f"stage3 widened guard domain: {level}")
        target = r121.aq(level * DELTA)
        left_sign = r121.strict_sign(
            c123.u3_value(seed, t_guard, a3_zero, lower, lower) - target
        )
        right_sign = r121.strict_sign(
            c123.u3_value(seed, t_guard, a3_zero, upper, upper) - target
        )
        derivative = (
            -c123.adapted3(seed, t_guard, lower, upper).gradient[0]
            / r121.aq(DELTA)
        )
        d_lower, d_upper = arb_bounds(derivative)
        require((left_sign, right_sign) == (-1, 1), f"stage3 family signs: {level}")
