def safe_output_path(path: Path) -> Path:
    expanded = path.expanduser()
    protected = {
        item.resolve()
        for item in (
            ROUND129,
            ROUND129_PRODUCER,
            ROUND129_VERIFIER,
            ROUND129_VERIFICATION,
            ROUND123,
            ROUND123_PRODUCER,
            ROUND123_COMMON,
            ROUND123_VERIFICATION,
            ROUND124,
            ROUND124_PRODUCER,
            ROUND124_VERIFICATION,
            ROUND125,
            ROUND125_PRODUCER,
            ROUND125_VERIFICATION,
            ROUND126,
            ROUND126_PRODUCER,
            ROUND126_VERIFICATION,
            ROUND121_PRODUCER,
            ROUND122_PRODUCER,
        )
    }
    require(not expanded.is_symlink(), "output path must not be a symlink")
    if expanded.exists():
        metadata = expanded.lstat()
        require(
            stat.S_ISREG(metadata.st_mode),
            "existing output must be a regular file",
        )
        require(
            metadata.st_nlink == 1,
            "existing output must not have multiple hardlinks",
        )
        for protected_path in protected:
            try:
                require(
                    not os.path.samefile(expanded, protected_path),
                    "output hardlinks a protected input",
                )
            except FileNotFoundError:
                pass
    resolved = expanded.resolve()
    require(resolved not in protected, "output must not overwrite an input")
    require(resolved.parent.is_dir(), "output parent directory")
    return resolved


def write_certificate(path: Path, result: dict[str, Any]) -> None:
    document = {
        "schema": SCHEMA,
        "result": result,
        "result_sha256": digest(result),
    }
    text = json.dumps(
        document,
        sort_keys=True,
        indent=2,
        ensure_ascii=False,
        allow_nan=False,
    ) + "\n"
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{path.name}.tmp-",
        dir=path.parent,
        text=True,
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    except BaseException:
        try:
            temporary.unlink()
        except FileNotFoundError:
            pass
        raise


